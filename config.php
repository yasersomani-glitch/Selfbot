| بررسی تنظیمات ضروری
|--------------------------------------------------------------------------
*/

function validateConfig(): void
{
    $errors = [];

    if (BOT_TOKEN === '') {
        $errors[] = 'BOT_TOKEN تنظیم نشده است.';
    }

    if (OWNER_ID <= 0) {
        $errors[] = 'OWNER_ID تنظیم نشده است.';
    }

    if (DATABASE_URL === '') {
        $errors[] = 'DATABASE_URL تنظیم نشده است.';
    }

    if (!empty($errors)) {
        error_log(
            'CONFIG ERROR: ' . implode(' | ', $errors)
        );
    }
}

