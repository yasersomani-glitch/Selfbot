/*
|--------------------------------------------------------------------------
| تابع خواندن Environment Variable
|--------------------------------------------------------------------------
*/

function envValue(string $key, mixed $default = null): mixed
{
    $value = $_ENV[$key] ?? $_SERVER[$key] ?? null;

    if ($value === null || $value === '') {
        return $default;
    }

    return $value;
}

