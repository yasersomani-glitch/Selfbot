<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| CONFIG.PHP
|--------------------------------------------------------------------------
| تنظیمات اصلی ربات
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| توکن ربات پدر
|--------------------------------------------------------------------------
|
| در Render:
| PARENT_BOT_TOKEN = توکن ربات پدر
|
*/

define(
    'PARENT_BOT_TOKEN',
    trim(
        (string)(
            getenv('PARENT_BOT_TOKEN') ?: ''
        )
    )
);


/*
|--------------------------------------------------------------------------
| آیدی عددی مالک
|--------------------------------------------------------------------------
|
| در Render:
| OWNER_ID = 123456789
|
*/

define(
    'OWNER_ID',
    (int)(
        getenv('OWNER_ID') ?: 0
    )
);


/*
|--------------------------------------------------------------------------
| پشتیبانی
|--------------------------------------------------------------------------
|
| مثال:
| SUPPORT_USERNAME = support_username
|
| بدون @ وارد شود.
|
*/

define(
    'SUPPORT_USERNAME',
    trim(
        (string)(
            getenv('SUPPORT_USERNAME') ?: ''
        )
    )
);


/*
|--------------------------------------------------------------------------
| آدرس اصلی Render
|--------------------------------------------------------------------------
|
| مثال:
| https://mybot.onrender.com/index.php
|
*/

define(
    'WEBHOOK_URL',
    rtrim(
        trim(
            (string)(
                getenv('WEBHOOK_URL') ?: ''
            )
        ),
        '/'
    )
);


/*
|--------------------------------------------------------------------------
| مسیر دیتابیس
|--------------------------------------------------------------------------
*/

define(
    'DATABASE_PATH',
    __DIR__ . '/database.sqlite'
);


/*
|--------------------------------------------------------------------------
| هزینه ساخت ربات
|--------------------------------------------------------------------------
*/

define(
    'BOT_CREATE_COST',
    5
);


/*
|--------------------------------------------------------------------------
| پاداش زیرمجموعه
|--------------------------------------------------------------------------
*/

define(
    'REFERRAL_REWARD',
    1
);


/*
|--------------------------------------------------------------------------
| منطقه زمانی
|--------------------------------------------------------------------------
*/

date_default_timezone_set(
    'Asia/Kabul'
);


/*
|--------------------------------------------------------------------------
| حالت Debug
|--------------------------------------------------------------------------
|
| روی Render بهتر است خاموش باشد.
|
*/

define(
    'DEBUG_MODE',
    false
);


/*
|--------------------------------------------------------------------------
| گزارش خطا
|--------------------------------------------------------------------------
*/

if (
    DEBUG_MODE
) {

    error_reporting(
        E_ALL
    );

    ini_set(
        'display_errors',
        '1'
    );

} else {

    error_reporting(
        E_ALL
    );

    ini_set(
        'display_errors',
        '0'
    );
}


/*
|--------------------------------------------------------------------------
| بررسی تنظیمات ضروری
|--------------------------------------------------------------------------
*/

if (
    PARENT_BOT_TOKEN === ''
) {

    error_log(
        'ERROR: PARENT_BOT_TOKEN is not configured.'
    );
}


if (
    OWNER_ID <= 0
) {

    error_log(
        'ERROR: OWNER_ID is not configured.'
    );
}


/*
|--------------------------------------------------------------------------
| تنظیمات پروژه
|--------------------------------------------------------------------------
*/

define(
    'PROJECT_NAME',
    'Music Bot Builder'
);


/*
|--------------------------------------------------------------------------
| نسخه
|--------------------------------------------------------------------------
*/

define(
    'PROJECT_VERSION',
    '1.0.0'
);
