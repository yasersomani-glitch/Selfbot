<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| WEBHOOK.PHP
|--------------------------------------------------------------------------
| ورودی اصلی Telegram برای ربات پدر و ربات‌های فرزند
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/config.php';
require_once __DIR__ . '/database.php';
require_once __DIR__ . '/functions.php';
require_once __DIR__ . '/telegram.php';
require_once __DIR__ . '/parent.php';
require_once __DIR__ . '/child.php';
require_once __DIR__ . '/music.php';


/*
|--------------------------------------------------------------------------
| دریافت Update
|--------------------------------------------------------------------------
*/

$rawUpdate = file_get_contents('php://input');

if (
    !is_string($rawUpdate) ||
    trim($rawUpdate) === ''
) {

    http_response_code(200);

    echo 'OK';

    exit;
}


$update = json_decode(
    $rawUpdate,
    true
);


if (
    !is_array($update)
) {

    http_response_code(400);

    echo 'Invalid update';

    exit;
}


/*
|--------------------------------------------------------------------------
| تشخیص پیام / Callback
|--------------------------------------------------------------------------
*/

$message = $update['message'] ?? null;

$callback = $update['callback_query'] ?? null;


/*
|--------------------------------------------------------------------------
| اطلاعات عمومی Update
|--------------------------------------------------------------------------
*/

$chatId = null;

$userId = null;

$from = [];


/*
|--------------------------------------------------------------------------
| Message
|--------------------------------------------------------------------------
*/

if (
    is_array($message)
) {

    $chatId =
        $message['chat']['id'] ?? null;

    $from =
        $message['from'] ?? [];

    $userId =
        $from['id'] ?? $chatId;
}


/*
|--------------------------------------------------------------------------
| Callback Query
|--------------------------------------------------------------------------
*/

if (
    is_array($callback)
) {

    $from =
        $callback['from'] ?? [];

    $userId =
        $from['id'] ?? null;

    $chatId =
        $callback['message']['chat']['id']
        ?? null;
}


/*
|--------------------------------------------------------------------------
| اگر Chat ID وجود نداشت
|--------------------------------------------------------------------------
*/

if (
    $chatId === null
) {

    http_response_code(200);

    echo 'OK';

    exit;
}


/*
|--------------------------------------------------------------------------
| تبدیل به Integer
|--------------------------------------------------------------------------
*/

$chatId =
    (int)$chatId;

$userId =
    (int)$userId;


/*
|--------------------------------------------------------------------------
| تشخیص رباتی که Webhook برای آن فراخوانی شده
|--------------------------------------------------------------------------
|
| هنگام ساخت Webhook، شناسه ربات در URL قرار می‌گیرد:
|
| webhook.php?bot=BOT_ID
|
|--------------------------------------------------------------------------
*/

$botId =
    isset($_GET['bot'])
        ? (int)$_GET['bot']
        : 0;


/*
|--------------------------------------------------------------------------
| اگر Bot ID از URL نبود
|--------------------------------------------------------------------------
*/

if (
    $botId <= 0
) {

    /*
    | امکان استفاده از token
    */

    $token =
        isset($_GET['token'])
            ? trim((string)$_GET['token'])
            : '';

    if (
        $token !== ''
    ) {

        $botId =
            findBotIdByToken(
                $token
            );
    }
}


/*
|--------------------------------------------------------------------------
| اگر ربات پیدا نشد
|--------------------------------------------------------------------------
*/

if (
    $botId <= 0
) {

    http_response_code(200);

    echo 'OK';

    exit;
}


/*
|--------------------------------------------------------------------------
| بررسی فعال بودن ربات
|--------------------------------------------------------------------------
*/

if (
    function_exists(
        'isBotActive'
    )
) {

    if (
        !isBotActive($botId)
    ) {

        http_response_code(200);

        echo 'OK';

        exit;
    }
}


/*
|--------------------------------------------------------------------------
| بررسی بلاک کاربر
|--------------------------------------------------------------------------
*/

if (
    $userId > 0 &&
    function_exists(
        'isUserBlocked'
    )
) {

    if (
        isUserBlocked($userId)
    ) {

        if (
            is_array($callback)
        ) {

            answerCallback(
                (string)$callback['id'],
                '🚫 حساب شما مسدود است.',
                true
            );
        }

        http_response_code(200);

        echo 'OK';

        exit;
    }
}


/*
|--------------------------------------------------------------------------
| Callback Query
|--------------------------------------------------------------------------
*/

if (
    is_array($callback)
) {

    $callbackId =
        (string)(
            $callback['id'] ?? ''
        );

    $data =
        (string)(
            $callback['data'] ?? ''
        );

    $messageId =
        (int)(
            $callback['message']['message_id']
            ?? 0
        );


    /*
    |--------------------------------------------------------------------------
    | مشخص کردن پدر یا فرزند
    |--------------------------------------------------------------------------
    */

    $botType =
        getBotType(
            $botId
        );


    /*
    |--------------------------------------------------------------------------
    | ربات پدر
    |--------------------------------------------------------------------------
    */

    if (
        $botType === 'parent'
    ) {

        handleParentCallback(
            $chatId,
            $userId,
            $callbackId,
            $data,
            $messageId
        );

    }

    /*
    |--------------------------------------------------------------------------
    | ربات فرزند
    |--------------------------------------------------------------------------
    */

    else {

        handleChildCallback(
            $chatId,
            $botId,
            $callbackId,
            $data,
            $messageId
        );
    }


    http_response_code(200);

    echo 'OK';

    exit;
}


/*
|--------------------------------------------------------------------------
| Message معمولی
|--------------------------------------------------------------------------
*/

if (
    is_array($message)
) {

    /*
    |--------------------------------------------------------------------------
    | ثبت / بروزرسانی کاربر
    |--------------------------------------------------------------------------
    */

    $firstName =
        (string)(
            $from['first_name'] ?? ''
        );

    $lastName =
        (string)(
            $from['last_name'] ?? ''
        );

    $username =
        (string)(
            $from['username'] ?? ''
        );


    if (
        function_exists(
            'createUser'
        )
    ) {

        createUser(
            $userId,
            $firstName,
            $lastName,
            $username
        );
    }


    /*
    |--------------------------------------------------------------------------
    | متن پیام
    |--------------------------------------------------------------------------
    */

    $text =
        isset($message['text'])
            ? trim(
                (string)$message['text']
            )
            : '';


    /*
    |--------------------------------------------------------------------------
    | تشخیص نوع ربات
    |--------------------------------------------------------------------------
    */

    $botType =
        getBotType(
            $botId
        );


    /*
    |--------------------------------------------------------------------------
    | ربات پدر
    |--------------------------------------------------------------------------
    */

    if (
        $botType === 'parent'
    ) {

        handleParentText(
            $chatId,
            $userId,
            $text,
            $message
        );

    }

    /*
    |--------------------------------------------------------------------------
    | ربات فرزند
    |--------------------------------------------------------------------------
    */

    else {

        /*
        | /start با اطلاعات کامل کاربر
        */

        if (
            $text === '/start' ||
            str_starts_with(
                $text,
                '/start '
            )
        ) {

            childStart(
                $chatId,
                $botId,
                $from
            );

        } else {

            handleChildText(
                $chatId,
                $botId,
                $text
            );
        }
    }


    http_response_code(200);

    echo 'OK';

    exit;
}


/*
|--------------------------------------------------------------------------
| Update ناشناخته
|--------------------------------------------------------------------------
*/

http_response_code(200);

echo 'OK';